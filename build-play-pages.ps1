# Builds "<adventure>/play.html" for each adventure folder: a full web page that links the
# folder's own style.css and code.js and embeds its index.html fragment. The three files in each
# folder stay exactly as they are for the Qollab editor. Re-run after editing any index.html:
#   powershell -ExecutionPolicy Bypass -File build-play-pages.ps1
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$utf8 = New-Object System.Text.UTF8Encoding $false
$adventures = @(
  @{ adv = 1; dir = "1st adventure"; title = "Adventure 1 &middot; Qubit basics" },
  @{ adv = 2; dir = "2nd adventure"; title = "Adventure 2 &middot; Grover's search" },
  @{ adv = 3; dir = "3rd adventure"; title = "Adventure 3 &middot; Ground-state hunters" }
)
foreach ($a in $adventures) {
  $dir = Join-Path $root $a.dir
  $fragment = [IO.File]::ReadAllText((Join-Path $dir "index.html"), $utf8)
  $page = @"
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Quantum Battlefield &middot; $($a.title)</title>
<!-- Generated by build-play-pages.ps1 from index.html; edit index.html, then re-run the script. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Lilita+One&family=Nunito:wght@400;600;700;800&display=swap">
<link rel="stylesheet" href="style.css">
<link rel="stylesheet" href="../launcher/play.css">
</head>
<body data-adv="$($a.adv)">
<a class="qb-home" href="../index.html#adv-$($a.adv)">&larr; Adventure map</a>
$fragment
<script src="../launcher/progress.js"></script>
<script src="code.js"></script>
<script src="../launcher/play.js"></script>
</body>
</html>
"@
  [IO.File]::WriteAllText((Join-Path $dir "play.html"), $page, $utf8)
  Write-Output "wrote $($a.dir)/play.html"
}
